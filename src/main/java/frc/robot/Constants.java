package frc.robot;

import edu.wpi.first.wpilibj.RobotBase;

/**
 * This class defines the runtime mode used by AdvantageKit. The mode is always "real" when running
 * on a roboRIO. Change the value of "simMode" to switch between "sim" (physics sim) and "replay"
 * (log replay from a file).
 */
public final class Constants {
  public static final Mode simMode = Mode.SIM;
  public static final Mode currentMode = RobotBase.isReal() ? Mode.REAL : simMode;

  /**
   * When true, every {@link frc.robot.util.TunableNumber} shows up under "/Tuning" in NetworkTables
   * so gains can be changed live from AdvantageScope or Elastic without redeploying. Leave this on
   * while learning/tuning, turn it off for competitions.
   */
  public static final boolean tuningMode = true;

  public static enum Mode {
    /** Running on a real robot. */
    REAL,

    /** Running a physics simulator. */
    SIM,

    /** Replaying from a log file. */
    REPLAY
  }

  // ======================================================================================
  // WHERE TO CHANGE THINGS
  //   Constants.java (this file)  - robot facts + driver feel + aiming + path following
  //   VisionConstants.java        - where the camera is mounted, vision trust (std devs)
  //   TunerConstants.java         - GENERATED by Tuner X (gear ratios, module positions, motor
  //                                 gains, max speed). Edit it by re-running Tuner X, or by hand
  //                                 with care.
  //   FieldConstants.java         - the field (tags, hub, example spots)
  // Anything made with TunableNumber can ALSO be changed live from the dashboard under
  // /Tuning/... without redeploying; copy the value you like back into the default here.
  // ======================================================================================

  /** Physical facts about the robot. */
  public static final class Robot {
    // TODO: confirm whether 120 lb includes the battery AND bumpers. PathPlanner wants the full
    // competition weight. These must also match src/main/deploy/pathplanner/settings.json
    // (robotMass, robotMOI, wheelCOF): the PathPlanner GUI reads that file, the robot code reads
    // these.
    public static final double MASS_KG = 54.4; // 120 lb
    public static final double MOI_KG_M2 = 5.0; // Estimate; fine until paths are tuned seriously
    public static final double WHEEL_COF = 1.2; // Wheel tread coefficient of friction (estimate)
  }

  /** How the robot feels to drive with the joysticks. */
  public static final class Driver {
    public static final double DEADBAND = 0.1;

    /**
     * Fraction of the robot's top speed at full stick (1.0 = 4.5 m/s). The stick is also squared,
     * so half stick is only a quarter of this. Was 0.5, which felt sluggish.
     */
    public static final double TRANSLATION_SCALE = 0.8;

    /**
     * Turn rate at full right stick, in rad/s (6.28 = one spin per second). Set directly in rad/s
     * instead of as a fraction of top speed, so it does not depend on the module spacing.
     */
    public static final double MAX_OMEGA_RAD_PER_SEC = 7.0;
  }

  /** Turn-to-face-a-target controller (Y and A buttons). See AimController. */
  public static final class Aim {
    // Heading controller gains. kP is (rad/s of turning) per (rad of error).
    public static final double KP = 6.0;
    public static final double KD = 0.2;
    public static final double MAX_OMEGA_RAD_PER_SEC = 6.0;
    public static final double TOLERANCE_DEG = 2.0;

    /**
     * Smallest turn rate the robot is commanded when it is still off target. Without it, the P term
     * shrinks to almost nothing near the target (1 degree off at kP 6 = 0.1 rad/s = 3 cm/s at the
     * wheels), which is less than the wheels' static friction, so the robot just stops a few
     * degrees short. Raise it if the robot stalls short of the target; lower it if it buzzes/hunts.
     */
    public static final double MIN_OMEGA_RAD_PER_SEC = 0.35;

    /** The minimum-rate kick turns off inside this angle, so the robot can settle. */
    public static final double MIN_OMEGA_CUTOFF_DEG = 0.75;

    /** Ignore Limelight frames older than this (the pose history only goes back ~1.5 s). */
    public static final double MAX_FRAME_AGE_SECS = 0.5;

    /**
     * If the tx aim has not seen its locked tag for this long, it is allowed to pick a new tag. The
     * hub has two tags per face; without the lock the "best" tag can flip between them and the
     * robot jerks back and forth.
     */
    public static final double TAG_LOCK_TIMEOUT_SECS = 0.5;
  }

  /** PathPlanner path following and on-the-fly pathfinding. */
  public static final class Path {
    // Correction gains. Translation kP = (m/s) per meter of error; rotation kP = (rad/s) per rad.
    // Lower them if the robot oscillates around the path, raise them if it lags behind.
    public static final double TRANSLATION_KP = 5.0;
    public static final double ROTATION_KP = 5.0;

    // Speed limits for pathfinding (D-pad). Start slow!
    public static final double PATHFIND_MAX_VEL_MPS = 2.0;
    public static final double PATHFIND_MAX_ACCEL_MPS2 = 2.0;
    public static final double PATHFIND_MAX_ANG_VEL_DEG_PER_SEC = 360.0;
    public static final double PATHFIND_MAX_ANG_ACCEL_DEG_PER_SEC2 = 540.0;
  }

  /** CAN IDs for the non-drivetrain mechanisms (drivetrain IDs live in TunerConstants). */
  public static final class CanIds {
    public static final int FEED_MOTOR_1 = 15; // Intake roller (TalonSRX)
    public static final int FEED_MOTOR_2 = 16; // Intake roller (TalonSRX)
    public static final int FEED_MOVE_MOTOR = 10; // Intake deploy/retract (TalonSRX)
    public static final int TRANSFER_MOTOR = 17; // Shooter transfer (TalonFX), shooter not in use
    public static final int LAUNCH_MOTOR = 18; // Shooter flywheel (TalonFX), shooter not in use
  }

  /** roboRIO DIO ports. */
  public static final class DioPorts {
    public static final int INTAKE_LIMIT_FRONT = 0;
    public static final int INTAKE_LIMIT_BACK = 1;
  }
}
